// Helper function to get a date within current week at a specific time
const getDateInWeek = (daysOffset: number, hour: number = 9, minute: number = 0) => {
  const date = new Date()
  date.setDate(date.getDate() + daysOffset)
  date.setHours(hour, minute, 0, 0)
  return date.toISOString()
}

